"""
preauth/schema.py — the pre-authorisation request as typed Pydantic models.

WHY a strict schema?
  An auto-filled form is only useful if every field is either (a) copied from
  the FHIR record, (b) computed by the rule engine, or (c) generated by the LLM
  and visibly marked as such. The schema keeps those apart:
      patient / coverage / encounter / diagnoses  -> from FHIR (deterministic)
      coverage_check                              -> rule engine (deterministic)
      required_justification / clinical_...       -> LLM (or template), with citations
`to_fhir_claim()` emits a FHIR R4 Claim with use="preauthorization", which is
how pre-auth is exchanged in FHIR-based systems (e.g. NHCX-style flows in India).
"""
from __future__ import annotations

from pydantic import BaseModel, Field


class PatientInfo(BaseModel):
    patient_id: str
    name: str
    gender: str
    birth_date: str
    age: int | None = None
    phone: str = ""
    address: str = ""


class CoverageInfo(BaseModel):
    coverage_id: str
    policy_number: str | None = None
    plan_code: str
    plan_name: str
    insurer: str
    policy_start: str
    sum_insured_inr: int
    synthesized: bool = Field(False, description="True if plan was assigned by the parser (Synthea has no Indian Coverage)")


class EncounterInfo(BaseModel):
    encounter_id: str
    encounter_class: str
    type: str
    start: str
    end: str
    provider_org: str
    treating_doctor: str


class Diagnosis(BaseModel):
    code: str | None
    system: str = "http://snomed.info/sct"
    display: str
    onset: str | None = None
    is_primary: bool = False


class CoverageCheck(BaseModel):
    covered: bool
    preauth_required: bool
    category: str
    sublimit_inr: int | None = None
    ped_status: str
    violations: list[dict] = []


class Citation(BaseModel):
    chunk_id: str
    source: str
    section: str
    quote: str


class PreAuthRequest(BaseModel):
    request_id: str
    created_at: str
    status: str = "DRAFT"                       # a human must review before submission
    patient: PatientInfo
    coverage: CoverageInfo | None
    encounter: EncounterInfo
    diagnoses: list[Diagnosis]
    requested_service: str
    requested_service_code: str | None = None
    estimated_cost_inr: float
    coverage_check: CoverageCheck | None
    required_justification: list[str] = []      # what the insurer's policy says must be shown
    clinical_justification: str = ""            # draft medical-necessity statement
    missing_information: list[str] = []
    citations: list[Citation] = []
    generated_by: str = ""                      # "ollama/llama3.1:8b" or "template"
    decision_id: str | None = None              # audit-log record for this draft

    def to_fhir_claim(self) -> dict:
        primary = next((d for d in self.diagnoses if d.is_primary), self.diagnoses[0] if self.diagnoses else None)
        return {
            "resourceType": "Claim",
            "status": "draft",
            "use": "preauthorization",
            "type": {"coding": [{"system": "http://terminology.hl7.org/CodeSystem/claim-type",
                                 "code": "institutional" if self.encounter.encounter_class == "IMP" else "professional"}]},
            "patient": {"reference": f"Patient/{self.patient.patient_id}", "display": self.patient.name},
            "created": self.created_at,
            "provider": {"display": self.encounter.provider_org},
            "priority": {"coding": [{"code": "stat" if self.encounter.encounter_class == "EMER" else "normal"}]},
            "insurance": [{"sequence": 1, "focal": True,
                           "coverage": {"reference": f"Coverage/{self.coverage.coverage_id}"} if self.coverage else {}}],
            "diagnosis": [{"sequence": i + 1, "diagnosisCodeableConcept": {
                "coding": [{"system": d.system, "code": d.code, "display": d.display}]}}
                for i, d in enumerate(self.diagnoses)],
            "item": [{"sequence": 1,
                      "productOrService": {"coding": [{"system": "http://snomed.info/sct",
                                                       "code": self.requested_service_code,
                                                       "display": self.requested_service}]},
                      "diagnosisSequence": [1] if primary else [],
                      "net": {"value": self.estimated_cost_inr, "currency": "INR"}}],
            "supportingInfo": [{"sequence": 1, "category": {"text": "clinical-justification"},
                                "valueString": self.clinical_justification}],
            "total": {"value": self.estimated_cost_inr, "currency": "INR"},
        }

"""
appeal/agent.py — AGENTIC RAG that drafts an appeal letter with citations.

    python -m appeal.agent <claim_id>

"Agentic" RAG vs plain RAG
  Plain RAG: embed the question → top-k chunks → one LLM call. One shot; if
  retrieval misses the decisive clause, the letter is weak and nobody notices.
  Agentic RAG puts the retrieval in a LOOP the agent controls:
    * it PLANS its own search queries from the denial reason,
    * it GRADES what came back and REWRITES queries if evidence is thin,
    * it DRAFTS, then VERIFIES its own citations, and REVISES once if needed.

GRAPH
  START → gather_context → plan_queries → retrieve → grade ─┬─(enough evidence)──→ draft → verify ─┬─(ok)─────→ finalize → END
                                             ▲              │                        ▲             │
                                             └─ rewrite ◀───┘(thin & attempts<2)     └── revise ◀──┘(issues & revisions<1)

Grounding rules enforced in code (not just in the prompt):
  * Every source has an id like [suraksha_silver_policy#5]. The letter may only
    cite ids that were retrieved AND graded relevant. `verify` checks this.
  * Claim facts (amount, dates, reason) come from the brain + rule engine, and
    are passed to the LLM as data, never generated by it.
  * Whether the appeal is *viable* is decided deterministically in
    gather_context: we re-run the insurer's rulebook. If the rule the insurer
    cited genuinely applies, the letter is marked WEAK and the orchestrator
    recommends fixing the claim instead of appealing.
"""
from __future__ import annotations

import json
import re
import sys
from datetime import date, datetime, timezone
from functools import lru_cache
from typing import TypedDict

from langgraph.graph import END, START, StateGraph

from brain.predict import get_brain
from core.llm import get_llm
from core.rag import retrieve
from data.reference import PLANS, REASON_CODES, evaluate_policy
from data.simulate_adjudication import build_claim_context
from trust.audit import record_decision

MAX_RETRIEVAL_ATTEMPTS = 2
MAX_REVISIONS = 1
MIN_POLICY_CHUNKS = 2


class AppealState(TypedDict, total=False):
    claim_id: str
    claim: dict
    denial: dict                 # {code, label, source: actual|predicted, risk}
    grounds: list[str]           # deterministic arguments from the rule engine
    viable: bool
    queries: list[str]
    attempts: int
    candidates: list[dict]       # all retrieved chunks
    evidence: list[dict]         # graded-relevant chunks
    draft: str
    draft_source: str            # "provider/model" or "template" (LLM unavailable/failed)
    issues: list[str]
    revisions: int
    result: dict



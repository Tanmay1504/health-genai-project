def _d(v) -> date | None:
    return date.fromisoformat(str(v)[:10]) if v not in (None, "", "nan") and str(v) != "nan" else None


def gather_context(state: AppealState) -> dict:
    brain = get_brain()
    row = brain.claim_row(state["claim_id"])
    pred = brain.denial(state["claim_id"])
    if row["denied"]:
        code, source = row["denial_reason"], "actual"
    else:
        code, source = pred["top_reasons"][0]["code"], "predicted"

    plan = PLANS[row["plan_code"]]
    ctx = build_claim_context(row, _d(row["coverage_start"]))
    violated = {v["code"]: v for v in evaluate_policy(ctx)}
    onset, cov_start = ctx["dx_onset"], ctx["coverage_start"]

    # Grounds: why the insurer's (actual or expected) reason does NOT hold.
    grounds: list[str] = []
    if code == "D03":
        if plan.ped_waiting_months == 0:
            grounds.append(f"{plan.name} has no pre-existing disease waiting period.")
        elif onset and onset >= cov_start:
            grounds.append(f"{row['dx_display']} was first diagnosed on {onset}, AFTER the policy start date "
                           f"{cov_start}; by definition it is not a Pre-Existing Disease, so the waiting period does not apply.")
    elif code == "D04" and ctx["docs_complete"]:
        grounds.append(f"All mandatory documents ({int(row['n_documents'])} items) were submitted with the claim; "
                       "no written request for further documents was received.")
    elif code == "D02" and "D02" not in violated:
        grounds.append(f"'{row['category']}' treatment in a {row['encounter_class']} setting is covered under {plan.name}.")
    elif code == "D05" and "D05" not in violated:
        lim = plan.sublimits_inr.get(row["category"])
        grounds.append(f"The claimed ₹{row['total_inr']:,.0f} is within the applicable limit"
                       + (f" of ₹{lim:,}." if lim else "; no sub-limit applies to this category."))
    elif code == "D01" and "D01" not in violated:
        grounds.append("Pre-authorisation was either obtained or not required for this claim.")
    elif code == "D06" and "D06" not in violated:
        grounds.append(f"The claim was submitted within {int(row['days_to_submit'])} days, inside the {plan.submission_days}-day limit.")
    viable = bool(grounds) and code != "D07"
    if not viable:
        grounds.append(f"Rule check: the cited reason ({code}) appears to genuinely apply"
                       + (f": {violated[code]['detail']}" if code in violated else "."))

    claim = {k: row[k] for k in ("claim_id", "patient_id", "name", "created", "total_inr", "encounter_class",
                                 "dx_display", "dx_onset", "procedure", "category", "plan_code", "coverage_start")}
    claim["plan_name"], claim["insurer"] = plan.name, plan.insurer
    return {"claim": claim, "grounds": grounds, "viable": viable, "attempts": 0, "revisions": 0,
            "denial": {"code": code, "label": REASON_CODES.get(code, code), "source": source,
                       "risk": pred["denial_risk"]}}


SYSTEM = """You are an expert health-insurance appeals writer for an Indian hospital.
You write factual, polite, firm appeals. You never invent facts, clause numbers or medical findings."""


def plan_queries(state: AppealState) -> dict:
    """The agent decides WHAT to search for. Fallback queries per reason code
    encode what an experienced appeals officer would look up."""
    c, d = state["claim"], state["denial"]
    fallback = {
        "D03": ["definition of pre-existing disease diagnosed before policy start",
                "pre-existing disease waiting period applies only", f"{c['dx_display']} diagnosis date newly diagnosed chronic"],
        "D04": ["insurer must request missing documents in writing before rejection", "mandatory documents claim"],
        "D02": [f"scope of cover {c['category']} outpatient day-care", "reasoned denial must state clause"],
        "D05": [f"{c['category']} sub-limit amount", "reasoned denial must state clause"],
        "D01": ["pre-authorisation emergency admission 24 hours", "when pre-authorisation is required"],
        "D06": ["condonation of delay genuine hardship", "time limit reimbursement claim"],
    }.get(d["code"], ["reasoned denial must state clause", "right to appeal"])
    fallback = fallback + [f"{c['dx_display']} {c['procedure']} medical necessity"]
    user = (f"Claim denied with reason {d['code']} ({d['label']}). Diagnosis: {c['dx_display']}. "
            f"Procedure: {c['procedure']}. Grounds we believe in: {state['grounds']}.\n"
            "Write 3-5 short search queries to find (a) policy clauses that rebut the denial and "
            "(b) clinical guidance on medical necessity. Return a JSON list of strings.")
    q = get_llm().complete_json(SYSTEM, user, default=fallback)
    q = [s for s in q if isinstance(s, str) and s.strip()][:5] or fallback
    return {"queries": q}


def retrieve_node(state: AppealState) -> dict:
    c = state["claim"]
    seen: dict[str, dict] = {ch["chunk_id"]: ch for ch in state.get("candidates", [])}
    for q in state["queries"]:
        for ch in retrieve(q, "policies", k=4, plan_code=c["plan_code"]):
            seen.setdefault(ch.chunk_id, ch.as_dict())
    # The diagnosis is repeated to weight it above the generic words "medical necessity".
    for ch in retrieve(f"{c['dx_display']} {c['dx_display']} {c['procedure']} medical necessity", "clinical", k=3):
        seen.setdefault(ch.chunk_id, ch.as_dict())
    return {"candidates": sorted(seen.values(), key=lambda x: x["score"]), "attempts": state["attempts"] + 1}


def grade(state: AppealState) -> dict:
    """LLM-as-grader: keep only chunks that actually help this appeal.
    Fallback: keep the nearest chunks by vector distance."""
    cands = state["candidates"]
    listing = "\n".join(f"[{c['chunk_id']}] {c['section']}: {c['text'][:350]}" for c in cands)
    user = (f"Denial reason: {state['denial']['code']} {state['denial']['label']}. Grounds: {state['grounds']}.\n"
            f"Candidate sources:\n{listing}\n\nReturn a JSON list of the chunk ids that are directly useful "
            "evidence for the appeal (policy definitions, rules, procedure standards, clinical necessity).")
    pol = [c for c in cands if c["collection"] == "policies"]
    clin = [c for c in cands if c["collection"] == "clinical"]
    fallback = [c["chunk_id"] for c in pol[:5] + clin[:2]]
    picked = get_llm().complete_json(SYSTEM, user, default=fallback)
    # Keep only plain-string ids that were really retrieved (LLMs sometimes return objects or invent ids).
    ids = {x for x in picked if isinstance(x, str)} & {c["chunk_id"] for c in cands}
    return {"evidence": [c for c in cands if c["chunk_id"] in (ids or set(fallback))]}


def route_after_grade(state: AppealState) -> str:
    n_policy = sum(1 for c in state["evidence"] if c["collection"] == "policies")
    if n_policy < MIN_POLICY_CHUNKS and state["attempts"] < MAX_RETRIEVAL_ATTEMPTS:
        return "rewrite"
    return "draft"


def rewrite(state: AppealState) -> dict:
    """Corrective step: broaden the queries when grading found too little."""
    d = state["denial"]
    broader = [f"{d['label']} policy clause", "standards for denial burden of proof",
               "right to appeal timelines", "definitions"]
    user = (f"These queries found too little policy evidence: {state['queries']}. "
            f"Write 3 broader queries for an appeal against '{d['label']}'. JSON list of strings.")
    q = get_llm().complete_json(SYSTEM, user, default=broader)
    return {"queries": [s for s in q if isinstance(s, str)][:4] or broader}


def _sources_block(ev: list[dict]) -> str:
    return "\n\n".join(f"[{c['chunk_id']}] ({c['source']} — {c['section']})\n{c['text']}" for c in ev)


def draft(state: AppealState) -> dict:
    c, d, ev = state["claim"], state["denial"], state["evidence"]
    user = f"""CLAIM FACTS (authoritative, do not alter):
{json.dumps(c, default=str, indent=2)}
DENIAL: {d['code']} — {d['label']} ({d['source']})
OUR GROUNDS (verified by rule engine): {json.dumps(state['grounds'])}

SOURCES (cite as [chunk_id] exactly as written):
{_sources_block(ev)}

Write the appeal letter to the insurer's grievance cell. Structure: subject line; claim details;
grounds for appeal (each paragraph must cite at least one source id in square brackets, e.g. [policy_file#3]);
clinical necessity; reference to denial standards; specific request (reprocess and pay);
closing. Plain text, no markdown headers or bold. Cite ONLY ids from SOURCES.
Clinical necessity: state only what a clinical source above supports and cite it; if no clinical
source applies, write that the treating doctor will attach clinical notes. Never add medical claims of your own.
Sign off exactly as: "Insurance Desk (on behalf of the treating provider)". Never use placeholders like [Your Name]."""
    if state.get("issues"):
        user += "\n\nYour previous draft had these problems; fix them:\n- " + "\n- ".join(state["issues"]) \
                + f"\n\nPREVIOUS DRAFT:\n{state['draft']}"
    llm = get_llm()
    text = llm.complete(SYSTEM, user)
    if text:
        return {"draft": text, "draft_source": f"{llm.provider}/{llm.model_name}"}
    return {"draft": _template_letter(state), "draft_source": "template"}


def _pick(ev: list[dict], *keywords: str) -> str | None:
    for c in ev:
        blob = (c["section"] + " " + c["text"]).lower()
        if any(k in blob for k in keywords):
            return c["chunk_id"]
    return None


def _template_letter(state: AppealState) -> str:
    """Deterministic letter used by the mock provider or when the LLM fails.
    Citations are chosen by keyword match within the graded evidence."""
    c, d, ev = state["claim"], state["denial"], state["evidence"]
    pol = [e for e in ev if e["collection"] == "policies"]
    clin = [e for e in ev if e["collection"] == "clinical"]
    key = {"D03": ("pre-existing", "waiting period"), "D04": ("documents",), "D02": ("scope", "cover"),
           "D05": ("sub-limit", "limit"), "D01": ("pre-authorisation",), "D06": ("delay", "time limit")}
    g_cite = _pick(pol, *key.get(d["code"], ("clause",))) or (pol[0]["chunk_id"] if pol else None)
    s_cite = _pick(pol, "reasoned denial", "burden of proof", "standards for denial") or g_cite
    a_cite = _pick(pol, "right to appeal", "appeal") or s_cite
    # Only cite clinical evidence that is actually about this diagnosis.
    dx_words = [w for w in re.findall(r"[a-z]+", str(c["dx_display"]).lower()) if len(w) > 4]
    k_cite = _pick(clin, *dx_words) if dx_words else None
    cite = lambda x: f" [{x}]" if x else ""  # noqa: E731
    return f"""To: The Grievance Redressal Cell, {c['insurer']}
Subject: Appeal against denial of claim {c['claim_id']} — {d['code']} {d['label']}

Dear Sir/Madam,

We write on behalf of our patient {c['name']} (policy: {c['plan_name']}) to appeal the {'denial' if d['source'] == 'actual' else 'anticipated denial'} of claim {c['claim_id']} dated {str(c['created'])[:10]} for ₹{float(c['total_inr']):,.0f}, relating to {c['dx_display']} ({c['procedure']}).

Grounds for appeal: {' '.join(state['grounds'])} The policy wording supports this position{cite(g_cite)}.

Clinical necessity: the treatment provided is consistent with accepted clinical practice for {c['dx_display']}{cite(k_cite) if k_cite else ' (treating doctor to attach supporting clinical notes)'}.

Denial standards: a denial must identify the clause relied on and the facts that bring the claim within it, and the insurer bears the burden of proving that an exclusion or waiting period applies{cite(s_cite)}.

Request: we request that the claim be reprocessed and paid in full, with interest for any delay, within the timelines for deciding appeals{cite(a_cite)}.

Yours faithfully,
Insurance Desk (on behalf of the treating provider)"""


CITE_RE = re.compile(r"\[([A-Za-z0-9_\-]+#\d+)\]")


def verify(state: AppealState) -> dict:
    """Deterministic self-check of the draft. No LLM: checks must not hallucinate."""
    text, ev = state["draft"], state["evidence"]
    allowed = {c["chunk_id"] for c in ev}
    cited = CITE_RE.findall(text)
    issues = []
    unknown = sorted(set(cited) - allowed)
    if unknown:
        issues.append(f"Cites sources that were not provided: {unknown}")
    if not cited:
        issues.append("No citations at all.")
    if state["claim"]["claim_id"] not in text:
        issues.append("Claim id missing from the letter.")
    # Paragraphs that state claim facts (they mention the claim id) come from our
    # own data, not from sources, so only argument paragraphs must carry citations.
    body = [p for p in text.split("\n\n") if len(p) > 200 and state["claim"]["claim_id"] not in p]
    uncited = [p[:60] for p in body if not CITE_RE.search(p)]
    if len(uncited) > 1:
        issues.append(f"{len(uncited)} substantive paragraphs have no citation.")
    return {"issues": issues}


def route_after_verify(state: AppealState) -> str:
    if state["issues"] and state["revisions"] < MAX_REVISIONS:
        return "revise"
    return "finalize"


def revise(state: AppealState) -> dict:
    return {"revisions": state["revisions"] + 1}


def finalize(state: AppealState) -> dict:
    text, ev = state["draft"], state["evidence"]
    # Strip any citation the verifier rejected, so the final letter cites only real sources.
    allowed = {c["chunk_id"] for c in ev}
    text = CITE_RE.sub(lambda m: m.group(0) if m.group(1) in allowed else "", text)
    used = sorted(set(CITE_RE.findall(text)))
    llm = get_llm()
    strength = "STRONG" if state["viable"] and not state["issues"] else "WEAK" if not state["viable"] else "NEEDS_REVIEW"
    result = {
        "claim_id": state["claim_id"], "denial": state["denial"], "grounds": state["grounds"],
        "appeal_strength": strength, "letter": text,
        "citations": [{"chunk_id": c["chunk_id"], "source": c["source"], "section": c["section"],
                       "quote": c["text"][:400]} for c in ev if c["chunk_id"] in used],
        "trace": {"queries": state["queries"], "retrieval_attempts": state["attempts"],
                  "revisions": state["revisions"], "unresolved_issues": state["issues"]},
        "generated_by": state.get("draft_source", "template"),
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    result["decision_id"] = record_decision(
        module="appeal", subject_id=state["claim_id"], recommendation=f"APPEAL_{strength}",
        inputs={"claim": state["claim"], "denial": state["denial"], "grounds": state["grounds"]},
        output={k: result[k] for k in ("appeal_strength", "letter", "trace")},
        model_name="appeal-agent", model_version=get_brain().version("denial_model"),
        llm=llm.describe() if state.get("draft_source", "template") != "template"
        else {"llm_provider": "template", "llm_model": "none"},
        retrieval=[{"chunk_id": c["chunk_id"], "source": c["source"], "score": c["score"],
                    "text": c["text"][:500]} for c in ev],
    )
    return {"result": result}


@lru_cache(maxsize=1)
def build_graph():
    g = StateGraph(AppealState)
    for name, fn in [("gather_context", gather_context), ("plan_queries", plan_queries),
                     ("retrieve", retrieve_node), ("grade", grade), ("rewrite", rewrite),
                     ("draft", draft), ("verify", verify), ("revise", revise), ("finalize", finalize)]:
        g.add_node(name, fn)
    g.add_edge(START, "gather_context")
    g.add_edge("gather_context", "plan_queries")
    g.add_edge("plan_queries", "retrieve")
    g.add_edge("retrieve", "grade")
    g.add_conditional_edges("grade", route_after_grade, {"rewrite": "rewrite", "draft": "draft"})
    g.add_edge("rewrite", "retrieve")          # the loop that makes it "agentic"
    g.add_edge("draft", "verify")
    g.add_conditional_edges("verify", route_after_verify, {"revise": "revise", "finalize": "finalize"})
    g.add_edge("revise", "draft")              # second loop: self-correction
    g.add_edge("finalize", END)
    return g.compile()


def run_appeal(claim_id: str) -> dict:
    return build_graph().invoke({"claim_id": claim_id})["result"]


if __name__ == "__main__":
    if len(sys.argv) < 2:
        raise SystemExit("usage: python -m appeal.agent <claim_id>")
    r = run_appeal(sys.argv[1])
    print(r["letter"], "\n\n", json.dumps({k: v for k, v in r.items() if k != "letter"}, indent=2, default=str))

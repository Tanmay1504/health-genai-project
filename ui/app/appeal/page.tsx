"use client";

// Appeal view: runs the agentic-RAG appeal agent, then shows the letter with
// inline citations, the sources each citation points to, and the agent's
// trace (queries tried, retrieval rounds, self-revisions).
import Link from "next/link";
import { Fragment, useEffect, useState } from "react";
import ClaimPicker from "@/components/ClaimPicker";
import { AppealResult, Citation, DEMO, post, short } from "@/lib/api";
import { APPEAL, reasonTip, STRENGTH } from "@/lib/glossary";
import { useQueryParam } from "@/lib/useQueryParam";

const STRENGTH_STYLE: Record<string, string> = { STRONG: "good", NEEDS_REVIEW: "warn", WEAK: "bad" };

// Turn "[policy#3]" markers into highlighted anchors that jump to the source
// card; hovering one shows the quoted text right there.
function LetterText({ text, citations }: { text: string; citations: Citation[] }) {
  const byId = Object.fromEntries(citations.map((c) => [c.chunk_id, c]));
  const parts = text.split(/(\[[A-Za-z0-9_\-]+#\d+\])/g);
  return (
    <div className="letter">
      {parts.map((p, i) => {
        const m = p.match(/^\[([A-Za-z0-9_\-]+#\d+)\]$/);
        if (!m) return <Fragment key={i}>{p}</Fragment>;
        const c = byId[m[1]];
        const tip = c ? `${c.section}\n\n“${c.quote.replace(/^#+\s.*\n/gm, "").trim()}”` : APPEAL.cite;
        return <a key={i} className="cite" href={`#src-${m[1]}`} data-tip={tip}>{m[1]}</a>;
      })}
    </div>
  );
}

export default function AppealPage() {
  const [claimId, setClaimId] = useQueryParam("claim");
  const [r, setR] = useState<AppealResult | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");

  useEffect(() => setR(null), [claimId]);

  async function generate() {
    setBusy(true);
    setError("");
    try {
      setR(await post<AppealResult>("/appeal", { claim_id: claimId }));
    } catch (e) {
      setError(String(e));
    } finally {
      setBusy(false);
    }
  }

  if (!claimId) {
    return (
      <>
        <h1>Auto-appeal</h1>
        <p className="lede">
          Pick a denied (or likely-denied) claim. The agent plans its own searches over the insurer&apos;s policy and the
          clinical guidance, grades what it finds, drafts a letter that cites every argument, and checks its own citations.
        </p>
        <ClaimPicker onPick={setClaimId} />
      </>
    );
  }

  return (
    <>
      <div className="row">
        <h1>Appeal · <span className="mono">{short(claimId)}</span></h1>
        <span className="spacer" />
        <button onClick={() => setClaimId("")}>← choose another claim</button>
        <button className="primary" onClick={generate} disabled={busy}
          data-tip="The AI agent searches the policy, drafts a letter with citations, checks every citation, and fixes the draft if needed.">
          {busy ? "Agent working…" : r ? "Regenerate" : "Generate appeal"}
        </button>
      </div>
      <p className="lede">{DEMO ? "Demo: this letter was pre-generated by Groq (openai/gpt-oss-120b) with the real agent." : "With Groq this takes about 10 seconds. The agent may loop through retrieval and revision."}</p>
      {error && <div className="alert bad">{error}</div>}

      {r && (
        <div className="grid two">
          <div>
            <div className="row" style={{ marginBottom: 10 }}>
              <span className={`badge ${STRENGTH_STYLE[r.appeal_strength]}`} data-tip={`${APPEAL.strength}\n\n${STRENGTH[r.appeal_strength]}`}>{r.appeal_strength}</span>
              <span className="badge info" data-tip={`${reasonTip(r.denial.code)}\n\n${APPEAL.denialTag}`}>{r.denial.code} · {r.denial.source}</span>
              <span className="muted tipped" data-tip={APPEAL.generatedBy}>generated by {r.generated_by}</span>
            </div>
            <LetterText text={r.letter} citations={r.citations} />
          </div>
          <div className="grid" style={{ alignContent: "start" }}>
            <div className="panel">
              <h2 data-tip={APPEAL.grounds}>Grounds (rule engine)</h2>
              <ul className="clean">{r.grounds.map((g, i) => <li key={i}>{g}</li>)}</ul>
            </div>
            <div className="panel">
              <h2 data-tip={APPEAL.sources}>Sources cited</h2>
              {r.citations.length === 0 && <p className="muted">No citations.</p>}
              {r.citations.map((c) => (
                <div key={c.chunk_id} id={`src-${c.chunk_id}`} style={{ marginBottom: 10 }}>
                  <div><span className="cite">{c.chunk_id}</span> <span className="muted">{c.section}</span></div>
                  <div className="quote">{c.quote}</div>
                </div>
              ))}
            </div>
            <div className="panel">
              <h2 data-tip={APPEAL.trace}>Agent trace</h2>
              <dl className="kv">
                <dt data-tip={APPEAL.rounds}>Retrieval rounds</dt><dd>{r.trace.retrieval_attempts}</dd>
                <dt data-tip={APPEAL.revisions}>Self-revisions</dt><dd>{r.trace.revisions}</dd>
                <dt data-tip={APPEAL.issues}>Open issues</dt><dd>{r.trace.unresolved_issues.length ? r.trace.unresolved_issues.join("; ") : "none"}</dd>
              </dl>
              <h3 data-tip={APPEAL.queries}>Queries the agent wrote</h3>
              <ul className="clean">{r.trace.queries.map((q, i) => <li key={i} className="mono">{q}</li>)}</ul>
              <p className="muted" style={{ marginBottom: 0 }}>
                Audit: <Link href={`/audit?subject=${claimId}`} className="mono" data-tip="This letter, its sources and the model used were saved to the audit log.">{r.decision_id}</Link>
              </p>
            </div>
          </div>
        </div>
      )}
    </>
  );
}
